# 4. Pipeline Entry Point
# ==============================================================================

def run_judge(input_jsonl_path: str, output_jsonl_path: str, model_path: str):
    """
    Main entry point for pipeline processing.
    Now supports STREAMING input and output to handle large datasets and prevent data loss.
    """
    print(f"[Judge] Starting 3-Axis evaluation streaming: {input_jsonl_path} -> {output_jsonl_path}")

    # 1. Initialize Judge
    cfg = OutputOnlyJudgeCfg(repo_id=model_path, torch_dtype="float16")
    judge_model = OutputOnlyLocalQwenJudge(cfg)

    # 2. Pre-count lines for tqdm (Optional but good for UX)
    try:
        with open(input_jsonl_path, 'r', encoding='utf-8') as f:
            total_lines = sum(1 for line in f if line.strip())
    except FileNotFoundError:
        print(f"Error: Input file {input_jsonl_path} not found.")
        return

    # 3. Streaming Process
    stats = {}  # Count behaviors

    # Simultaneously open read and write files
    with open(input_jsonl_path, 'r', encoding='utf-8') as fin, \
            open(output_jsonl_path, 'w', encoding='utf-8') as fout:

        for line in tqdm(fin, total=total_lines, desc="Judging Output"):
            if not line.strip():
                continue

            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue

            output_text = rec.get("output", "")

            # [Crucial] Extract Intent for Alignment Check
            intent = rec.get("intent") or rec.get("txt") or rec.get("input_text") or "Unknown Request"

            # Call Judge
            res = judge_model.judge(output_text, intent=intent)

            # Update Record
            rec.update({
                "judge_result": res,
                "status": "Jailbroken" if res["is_jailbreak_success"] else res["behavior_type"]
            })

            # Stats Update
            beh = res["behavior_type"]
            stats[beh] = stats.get(beh, 0) + 1

            # WRITE IMMEDIATELY & FLUSH
            fout.write(json.dumps(rec, ensure_ascii=False) + "\n")
            fout.flush()

    # 4. Print Summary
    print("\n" + "=" * 60)
    print("       3-AXIS BEHAVIORAL REPORT")
    print("=" * 60)
    print(f"{'Behavior Type':<30} | {'Count':<6}")
    print("-" * 40)
    for k in sorted(stats.keys()):
        print(f"{k:<30} | {stats[k]:<6}")
    print("-" * 40)
    print(f"Results saved to {output_jsonl_path}")